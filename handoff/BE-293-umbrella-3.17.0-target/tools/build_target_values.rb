# Builds the private be293-target overlays from the sanitized examples and an operator input file
# that holds ONLY platform coordinates confirmed by the target-cluster operator (no credentials).
#
# Input file (copy values/target-platform.example.yaml to <name>.private.yaml and fill it):
#   dnsZone, ingressClass, externalDns (true|false), registryHost, imageRepository,
#   pullSecretName, vaultAddress, helmHooksApproved (true|false)
#
# Output (mode 600, git-ignored names required):
#   <out-dir>/values-be293-target.private.yaml        umbrella overlay
#   <out-dir>/values-be293-target-vault.private.yaml  Vault release overlay (cluster-default StorageClass)
#
# Usage: ruby tools/build_target_values.rb <target-platform.private.yaml> <out-dir>
# The chart guard re-validates everything at render time; this tool only fails earlier.
Encoding.default_external = Encoding::UTF_8 # tools must not depend on the caller locale (LANG may be unset in CI)
require 'yaml'
require 'fileutils'

input, out_dir = ARGV
abort 'usage: build_target_values.rb <target-platform.private.yaml> <out-dir>' unless input && out_dir
abort 'input file name must end in .private.yaml (git-ignored)' unless input.end_with?('.private.yaml')
root = File.expand_path('..', __dir__)
example = File.join(root, 'values/values-be293-target.example.yaml')
vault_example = File.join(root, '../BE-293-umbrella-3.17.0/values/values-be293-vault.example.yaml')

EXAMPLE_ZONE = 'be293.target.example.invalid'.freeze
EXAMPLE_REGISTRY = 'registry.example.invalid'.freeze
EXAMPLE_REPOSITORY = "#{EXAMPLE_REGISTRY}/be293/be293-images".freeze
RESERVED = /(\A|\.)(example|invalid|test|localhost|local|example\.com|example\.net|example\.org)\z/.freeze
DNS_NAME = /\A([a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?\.)+[a-z]([-a-z0-9]{0,61}[a-z0-9])?\z/.freeze
DNS1123 = /\A[a-z0-9]([-a-z0-9]*[a-z0-9])?\z/.freeze

cfg = YAML.safe_load(File.read(input)) || {}
errors = []
str = ->(k) { v = cfg[k]; v.is_a?(String) && !v.strip.empty? && !v.include?('<<') ? v.strip : (errors << "#{k} is required"; nil) }
bool = ->(k) { [true, false].include?(cfg[k]) ? cfg[k] : (errors << "#{k} must be true or false"; nil) }
zone = str.('dnsZone')
ingress_class = str.('ingressClass')
external_dns = bool.('externalDns')
registry = str.('registryHost')
repository = str.('imageRepository')
pull_secret = str.('pullSecretName')
vault_address = str.('vaultAddress')
hooks = bool.('helmHooksApproved')
errors << 'dnsZone must be a lower-case DNS name' if zone && zone !~ DNS_NAME
errors << 'dnsZone uses a reserved or example suffix' if zone && zone =~ RESERVED
errors << 'registryHost uses a reserved or example suffix' if registry && registry.sub(/:\d+\z/, '') =~ RESERVED
errors << 'imageRepository must start with registryHost/' if registry && repository && !repository.start_with?("#{registry}/")
errors << 'ingressClass must be a DNS-1123 name' if ingress_class && ingress_class !~ DNS1123
errors << 'pullSecretName must be a DNS-1123 name' if pull_secret && pull_secret !~ DNS1123
errors << 'vaultAddress must be an http(s) URL' if vault_address && vault_address !~ %r{\Ahttps?://[^\s/]+\z}
errors << 'helmHooksApproved must be true (hooks are part of the release)' if hooks == false
abort "invalid #{input}:\n  " + errors.join("\n  ") unless errors.empty?

text = File.read(example)
text = text.gsub(EXAMPLE_REPOSITORY, repository)
           .gsub(/(?<=repository: )be293\/be293-images$/, repository.sub("#{registry}/", ''))
           .gsub(EXAMPLE_REGISTRY, registry)
           .gsub(EXAMPLE_ZONE, zone)
           .gsub('<<SET-BY-OPERATOR:ingress-class>>', ingress_class)
           .gsub('<<SET-BY-OPERATOR:pull-secret-name>>', pull_secret)
           .gsub('<<SET-BY-OPERATOR:vault-address>>', vault_address)
values = YAML.safe_load(text, aliases: true)
values['be293']['target']['externalDns'] = external_dns
values['be293']['target']['helmHooksApproved'] = hooks
out = YAML.dump(values)
%w[example.invalid <<SET-BY-OPERATOR].each { |m| abort "unreplaced #{m} left in output" if out.include?(m) }

vault = YAML.safe_load(File.read(vault_example))
vault.fetch('vault').fetch('server').fetch('dataStorage')['storageClass'] = ''

FileUtils.mkdir_p(out_dir, mode: 0o700)
umbrella_out = File.join(out_dir, 'values-be293-target.private.yaml')
vault_out = File.join(out_dir, 'values-be293-target-vault.private.yaml')
File.write(umbrella_out, "# PRIVATE - generated by tools/build_target_values.rb. Keep out of Git.\n" + out, perm: 0o600)
File.write(vault_out, "# PRIVATE - generated by tools/build_target_values.rb. Keep out of Git.\n" + YAML.dump(vault), perm: 0o600)
puts "wrote #{umbrella_out}"
puts "wrote #{vault_out}"
puts 'next: render with the secrets overlay as the LAST -f file (see README.md)'
