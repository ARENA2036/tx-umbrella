# Derives the sanitized be293-target values example from the verified DEV example overlay.
# Maintainer tool: re-run it only when the DEV example changes, and review the diff.
#
# Applied changes, nothing else:
#   - profile k8s-dev-01 -> be293-target; the k8s-dev-01 `platform` block and the DEV-only
#     devVaultStaticTokens switch are dropped; be293.target carries the confirmed values
#     (namespace be293, ClusterIssuer letsencrypt-prod, cluster-default StorageClass);
#   - DEV DNS zone -> reserved example zone be293.target.example.invalid;
#   - DEV pull Secret name, ingress class and Vault address -> <<SET-BY-OPERATOR:...>> markers;
#   - every StorageClass value in the overlay -> "" (cluster default), including the DEV premium class;
#   - external Ingress BPNs taken from manifests/10-ingress-identityhub-legacy-did.yaml.
# The output fails the be293-target guard until tools/build_target_values.rb fills the markers.
#
# Usage: ruby tools/derive_target_example.rb <values-be293-dev.example.yaml> <manifests/10-*.yaml> <out.yaml>
Encoding.default_external = Encoding::UTF_8 # tools must not depend on the caller locale (LANG may be unset in CI)
require 'yaml'

dev_example, did_ingress, output = ARGV
abort 'usage: derive_target_example.rb <values-be293-dev.example.yaml> <10-ingress-identityhub-legacy-did.yaml> <out.yaml>' unless output

DEV_ZONE = 'be293.dev.example.invalid'.freeze
TARGET_EXAMPLE_ZONE = 'be293.target.example.invalid'.freeze
DEV_PULL_SECRET = 'be293-dockerhub-pull'.freeze
DEV_VAULT_ADDRESS = 'http://be293-vault:8200'.freeze

text = File.read(dev_example)
text = text.gsub(DEV_ZONE, TARGET_EXAMPLE_ZONE)
           .gsub(DEV_PULL_SECRET, '<<SET-BY-OPERATOR:pull-secret-name>>')
           .gsub(DEV_VAULT_ADDRESS, '<<SET-BY-OPERATOR:vault-address>>')
values = YAML.safe_load(text, aliases: true)

def each_storage_class(node, &block)
  case node
  when Hash
    node.each_key { |k| yield node, k if k == 'storageClass' }
    node.each_value { |v| each_storage_class(v, &block) }
  when Array then node.each { |v| each_storage_class(v, &block) }
  end
end
each_storage_class(values) { |parent, key| parent[key] = '' }

bpns = YAML.safe_load(File.read(did_ingress))['spec']['rules'].flat_map { |r| r['http']['paths'] }
           .map { |p| p['path'][%r{\A/(BPNL[0-9A-Z]{12})/did\.json\z}, 1] }
abort 'unexpected DID Ingress paths' if bpns.include?(nil) || bpns.empty?

dev = values.fetch('be293')
images = dev.fetch('privateImages')
values['be293'] = {
  'deploymentProfile' => 'be293-target',
  'coreDnsPatch' => { 'enabled' => false },
  'routing' => dev.fetch('routing'),
  'privateImages' => {
    'enabled' => true,
    'pullSecretName' => images.fetch('pullSecretName'),
    'registry' => images.fetch('registry'),
    'repository' => images.fetch('repository'),
    'requireDigestReferences' => true
  },
  'target' => {
    'namespace' => 'be293',
    'clusterIssuer' => 'letsencrypt-prod',
    'storageClassPolicy' => 'cluster-default',
    'dnsZone' => TARGET_EXAMPLE_ZONE,
    'ingressClass' => '<<SET-BY-OPERATOR:ingress-class>>',
    'externalDns' => nil,
    'registryHost' => images.fetch('registry'),
    'imageRepository' => images.fetch('repository'),
    'pullSecretName' => images.fetch('pullSecretName'),
    'vaultAddress' => '<<SET-BY-OPERATOR:vault-address>>',
    'vaultAuthMode' => dev.fetch('platform').fetch('vaultAuthMode'),
    'secretDelivery' => dev.fetch('platform').fetch('secretDelivery'),
    'helmHooksApproved' => false,
    'externalIngresses' => { 'identityHubDidBpns' => bpns }
  }
}

header = <<~TXT
  # SANITIZED EXAMPLE - NOT DEPLOYABLE. be293-target profile values for BE-293 Umbrella 3.17.0.
  # Generated by tools/derive_target_example.rb from ../BE-293-umbrella-3.17.0/values/values-be293-dev.example.yaml.
  # Confirmed by the target-cluster operator: namespace be293, ClusterIssuer letsencrypt-prod,
  # cluster-default StorageClass. Everything else is a reserved example name (example.invalid)
  # or a <<SET-BY-OPERATOR:...>> marker, and the chart guard rejects both. Do not edit by hand:
  # build the private overlay with tools/build_target_values.rb. Credentials come from the
  # secrets overlay (../BE-293-umbrella-3.17.0/values/values-be293-dev.secrets.example.yaml).
TXT
File.write(output, header + YAML.dump(values).sub(/\A---\n/, ''))
puts "wrote #{output} (identity-hub DID BPNs: #{bpns.size})"
