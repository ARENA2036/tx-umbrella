# Builds the secrets-overlay template: every values subtree that contains a
# "<<SET-FROM-SECRET-STORE:...>>" placeholder, in chart-values then overlay order.
# Lists are copied whole (Helm replaces lists, it does not merge them).
# Usage: ruby secrets_example.rb <chart values.yaml> <overlay.yaml> <out.yaml>
require 'yaml'
PH = /\A<<SET-FROM-SECRET-STORE:/
def has_ph?(o) case o when Hash then o.values.any? { |v| has_ph?(v) } when Array then o.any? { |v| has_ph?(v) } else o.is_a?(String) && o =~ PH end end
def extract(o) case o
  when Hash then o.each_with_object({}) { |(k, v), h| h[k] = (v.is_a?(Array) ? v : extract(v)) if has_ph?(v) }
  else o end end
def prune(t, ov) return t unless ov.is_a?(Hash); t.each_with_object({}) { |(k, v), h| next if ov.key?(k) && !(v.is_a?(Hash) && ov[k].is_a?(Hash)); h[k] = (v.is_a?(Hash) && ov[k].is_a?(Hash)) ? prune(v, ov[k]) : v }.reject { |_, v| v.is_a?(Hash) && !has_ph?(v) } end
def merge(a, b) a.merge(b) { |_, x, y| x.is_a?(Hash) && y.is_a?(Hash) ? merge(x, y) : y } end
chart = YAML.safe_load(File.read(ARGV[0]), aliases: true); overlay = YAML.safe_load(File.read(ARGV[1]), aliases: true)
# Chart-default placeholders are dropped wherever the overlay sets that path (the overlay wins in Helm).
out = merge(prune(extract(chart), overlay), extract(overlay))
count = 0; walk = ->(o) { case o when Hash then o.each_value(&walk) when Array then o.each(&walk) else count += 1 if o.is_a?(String) && o =~ PH end }; walk.(out)
File.write(ARGV[2], <<~H + out.to_yaml.sub(/\A---\n/, ''))
  # TEMPLATE ONLY - NOT DEPLOYABLE. Generated by tools/secrets_example.rb.
  # Copy to a file named *.secrets.yaml OUTSIDE Git (or in this directory; it is git-ignored),
  # replace every "<<SET-FROM-SECRET-STORE:...>>" placeholder with the value from the approved
  # secret store, and pass it as the LAST -f file. Lists are complete: keep all entries.
  # Placeholders: #{count}. Label prefix: umbrella-defaults = chart values.yaml, dev-overlay = revision 21 overrides.
H
puts "placeholders in template: #{count}"
